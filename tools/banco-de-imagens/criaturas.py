def P(x, y, s, pts):
    return [(x + px * s, y + py * s) for px, py in pts]


def eyes(c, pts, color=(255, 80, 60), r=2.2):
    for ex, ey in pts:
        c.glow(ex, ey, r * 4, color, alpha=0.5)
        c.ellipse(ex, ey, r, r * 0.8, light(color, 0.6))


