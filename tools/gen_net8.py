# Generates net8/<Project>.Net8.csproj from the old csproj in src/<Project>: same source files, compiled for .NET 8.
# The old projects (and the Apolo.exe of today) are not touched.
import xml.etree.ElementTree as ET
NS = '{http://schemas.microsoft.com/developer/msbuild/2003}'

def pk(name, ver):
    return '    <PackageReference Include="%s" Version="%s" />' % (name, ver)

def gen(name, refs=(), packages=(), shim=None, csproj=None, forms=False, exclude=(), only=None, noresources=False, exe=False, extra_props=''):
    csproj = csproj or name
    root = ET.parse('src/%s/%s.csproj' % (name, csproj)).getroot()
    comp, res = [], []
    for g in root.findall(NS + 'ItemGroup'):
        for c in g.findall(NS + 'Compile'):
            if c.get('Include') not in exclude and (only is None or c.get('Include') in only):
                comp.append(c.get('Include'))
        for r in ([] if noresources else g.findall(NS + 'EmbeddedResource')):
            ln = r.find(NS + 'LogicalName')
            res.append((r.get('Include'), ln.text if ln is not None else None))
    ns = None
    asm = name
    for e in root.iter(NS + 'RootNamespace'):
        ns = e.text
    for e in root.iter(NS + 'AssemblyName'):
        asm = e.text
    out = ['<Project Sdk="Microsoft.NET.Sdk">',
           '  <!-- GENERATED by tools/gen_net8.py from src/%s/%s.csproj: the same files, built for .NET 8 (test of the migration). -->' % (name, csproj),
           '  <PropertyGroup>',
           '    <TargetFramework>net8.0-windows</TargetFramework>',
           '    <AssemblyName>%s</AssemblyName>' % asm,
           '    <RootNamespace>%s</RootNamespace>' % ns,
           '    <UseWindowsForms>true</UseWindowsForms>',
           ('    <OutputType>WinExe</OutputType>\n    <PlatformTarget>x86</PlatformTarget>\n    <ApplicationIcon>..\\src\\%s\\Resources\\Ares.ico</ApplicationIcon>' % name) if exe else '    <OutputType>Library</OutputType>',
           '    <EnableDefaultItems>false</EnableDefaultItems>',
           '    <GenerateAssemblyInfo>false</GenerateAssemblyInfo>',
           '    <ImplicitUsings>disable</ImplicitUsings>',
           '    <Nullable>disable</Nullable>',
           '    <NoWarn>$(NoWarn);CS0649;CS0168;CS0169;CS0414;CS0618;CS0219;CS0108;CS0114;CA1416;CA1418;SYSLIB0003;SYSLIB0011;SYSLIB0050;SYSLIB0051;WFO1000;NU1701</NoWarn>',
           '    <AppendTargetFrameworkToOutputPath>false</AppendTargetFrameworkToOutputPath>',
           '    <OutputPath>bin\\</OutputPath>',
           '  </PropertyGroup>', '  <ItemGroup>']
    for c in comp:
        out.append('    <Compile Include="..\\src\\%s\\%s" Link="%s" />' % (name, c, c))
    for sh in ([shim] if isinstance(shim, str) else (shim or [])):
        out.append('    <Compile Include="shims\\%s" />' % sh)
    for r, ln in res:
        if ln:
            out.append('    <EmbeddedResource Include="..\\src\\%s\\%s" LogicalName="%s" />' % (name, r, ln))
        else:
            out.append('    <EmbeddedResource Include="..\\src\\%s\\%s" Link="%s" />' % (name, r, r))
    out.append('  </ItemGroup>')
    if refs:
        out.append('  <ItemGroup>')
        for r in refs:
            out.append('    <ProjectReference Include="%s.Net8.csproj" />' % r)
        out.append('  </ItemGroup>')
    if packages:
        out.append('  <ItemGroup>')
        for p in packages:
            out.append(pk(*p))
        out.append('  </ItemGroup>')
    out.append('</Project>')
    open('net8/%s.Net8.csproj' % csproj, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print(name, len(comp), 'files', len(res), 'resources')

